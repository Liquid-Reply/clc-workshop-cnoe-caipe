#!/usr/bin/env bash
# Maintainer tool: regenerate bootstrap/images.lock from the images the RUNNING cluster uses.
# Run after a clean ./bootstrap/up.sh whenever versions.env or the stack changes.
# Each line is "<tag ref> <multi-arch index digest>", so one lock serves arm64 and amd64.
set -euo pipefail
cd "$(dirname "$0")"
source versions.env
# kube-system images, kindnet and local-path ship inside kindest/node, so they are not pulled at runtime
skip='^(registry\.k8s\.io/(kube-|etcd|coredns/)|docker\.io/kindest/(kindnetd|local-path)|workshop/)' # workshop/* is built locally by prepull.sh
{
  echo "# <ref> <index digest>. Generated by lock-images.sh; do not edit by hand."
  {
    echo "docker.io/$KIND_NODE_IMAGE"
    kubectl get pods -A -o jsonpath='{range .items[*]}{range .spec.containers[*]}{.image}{"\n"}{end}{range .spec.initContainers[*]}{.image}{"\n"}{end}{end}'
    # install/upgrade hook Jobs are usually deleted by now; read their images from the releases (test hooks never run)
    helm list -A --no-headers | while read -r name ns _; do
      helm get hooks "$name" -n "$ns" | awk '
        /^---/ { if (hook !~ /test/) for (i in img) print i; delete img; hook = ""; next }
        /"?helm\.sh\/hook"?:/ { hook = $2 }
        /^ *(- )?image:/ { gsub(/"/, "", $NF); img[$NF] }
        END { if (hook !~ /test/) for (i in img) print i }'
    done
  } | sed 's/@sha256:.*//' | grep -Ev "$skip" | sort -u | while read -r ref; do
    # index digest = sha256 of the raw index: one request per image (resolving every child manifest trips ECR Public's
    # anonymous rate limit), and no early-closed pipe (awk '...; exit' killed docker on long manifest lists under pipefail)
    digest=sha256:$(docker buildx imagetools inspect --raw "$ref" </dev/null | openssl dgst -sha256 -r | cut -d' ' -f1)
    # sha256 of empty input: docker printed nothing
    [ "$digest" != sha256:e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855 ] || { echo "cannot resolve $ref" >&2; exit 1; }
    echo "$ref $digest"
  done
} > images.lock.tmp # a failed run must not leave a truncated lock behind
mv images.lock.tmp images.lock
wc -l < images.lock | xargs echo "locked images (incl. header):"
